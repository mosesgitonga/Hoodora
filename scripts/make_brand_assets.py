"""Draws every Hoodora icon from the mark's geometry.

    uv run python scripts/make_brand_assets.py

The mark is a white centre dot in a ring of eight smaller dots. The one at the
top right is larger and navy: you, among neighbours. Everything is drawn here
from that geometry, rather than copied from exported files, so the images are
reproducible and carry no embedded metadata. Writes:

- Android: launcher icons (adaptive with a themed-icon layer, plus PNGs for old
  versions), the notification icon, and the launch-screen mark;
- iOS: every AppIcon size;
- docs/brand: the Play Store icon and clean SVGs of the icon, mark and logo.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
ANDROID_RES = ROOT / "mobile/android/app/src/main/res"
IOS_ICONS = ROOT / "mobile/ios/Runner/Assets.xcassets/AppIcon.appiconset"
BRAND = ROOT / "docs/brand"

ORANGE_TOP = (0xFF, 0x7A, 0x1A)
ORANGE_BOTTOM = (0xE8, 0x48, 0x0C)
ORANGE_LIGHT = "#FF7A1A"
ORANGE = "#E8480C"
NAVY = "#1E1B3A"
CREAM = "#FFF8F2"
WHITE = "#FFFFFF"

# The mark, in units of the full icon (1 = the icon's width).
RING = 0.27
"""The ring's radius, from the centre to each outer dot's centre."""
CENTRE_DOT = 0.105
OUTER_DOT = 0.052
ACCENT_DOT = 0.0754
ACCENT_ANGLE = -45
"""Degrees, screen coordinates: the top-right dot."""
CORNER = 0.225
"""The rounded icon's corner radius."""


def mark(scale: float = 1.0, *, dots: str, accent: str) -> list[tuple[float, float, float, str]]:
    """The mark's circles as (x, y, radius, colour) in a unit square, shrunk
    around the centre by `scale`."""
    circles = [(0.5, 0.5, CENTRE_DOT * scale, dots)]
    for step in range(8):
        angle = -90 + step * 45
        x = 0.5 + RING * scale * math.cos(math.radians(angle))
        y = 0.5 + RING * scale * math.sin(math.radians(angle))
        if angle == ACCENT_ANGLE:
            circles.append((x, y, ACCENT_DOT * scale, accent))
        else:
            circles.append((x, y, OUTER_DOT * scale, dots))
    return circles


# ---------------------------------------------------------------------------
# PNGs
# ---------------------------------------------------------------------------
SUPERSAMPLE = 4


def _gradient(size: int) -> Image.Image:
    image = Image.new("RGB", (size, size))
    draw = ImageDraw.Draw(image)
    for y in range(size):
        t = y / max(size - 1, 1)
        colour = tuple(
            round(a + (b - a) * t) for a, b in zip(ORANGE_TOP, ORANGE_BOTTOM, strict=True)
        )
        draw.line([(0, y), (size, y)], fill=colour)
    return image


def icon_png(size: int, *, shape: str) -> Image.Image:
    """The app icon: white mark on the orange gradient. `shape` is `square`
    (full bleed, for stores and iOS), `rounded` or `circle`."""
    big = size * SUPERSAMPLE
    image = _gradient(big).convert("RGBA")
    draw = ImageDraw.Draw(image)
    for x, y, r, colour in mark(dots=WHITE, accent=NAVY):
        draw.ellipse([(x - r) * big, (y - r) * big, (x + r) * big, (y + r) * big], fill=colour)
    if shape != "square":
        mask = Image.new("L", (big, big), 0)
        mask_draw = ImageDraw.Draw(mask)
        if shape == "circle":
            mask_draw.ellipse([0, 0, big - 1, big - 1], fill=255)
        else:
            mask_draw.rounded_rectangle([0, 0, big - 1, big - 1], radius=CORNER * big, fill=255)
        image.putalpha(mask)
    image = image.resize((size, size), Image.Resampling.LANCZOS)
    return image if shape != "square" else image.convert("RGB")


def save_png(image: Image.Image, path: Path) -> None:
    """Saved with nothing but the pixels: no text chunks, no metadata."""
    path.parent.mkdir(parents=True, exist_ok=True)
    # Drawn here, so there is no source metadata; and Pillow writes none unless
    # given `pnginfo`.
    image.save(path, format="PNG", optimize=True)


# ---------------------------------------------------------------------------
# Vector drawables and SVGs
# ---------------------------------------------------------------------------
def _circle_path(x: float, y: float, r: float) -> str:
    arc = f"a{r:.3f},{r:.3f} 0 1,0"
    return f"M{x - r:.3f},{y:.3f}{arc} {2 * r:.3f},0{arc} {-2 * r:.3f},0"


def vector_drawable(
    circles: list[tuple[float, float, float, str]], *, dp: int, viewport: float, comment: str
) -> str:
    paths = "\n".join(
        f'    <path android:fillColor="{colour}" android:pathData="'
        f'{_circle_path(x * viewport, y * viewport, r * viewport)}" />'
        for x, y, r, colour in circles
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {comment} Generated by scripts/make_brand_assets.py. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{dp}dp"\n    android:height="{dp}dp"\n'
        f'    android:viewportWidth="{viewport:g}"\n    android:viewportHeight="{viewport:g}">\n'
        f"{paths}\n</vector>\n"
    )


GRADIENT_BACKGROUND = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- The launcher icon's background: the brand's orange, lighter at the top.
     Generated by scripts/make_brand_assets.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="54" android:startY="0"
                android:endX="54" android:endY="108"
                android:startColor="{ORANGE_LIGHT}"
                android:endColor="{ORANGE}" />
        </aapt:attr>
    </path>
</vector>
"""

ADAPTIVE_ICON = """<?xml version="1.0" encoding="utf-8"?>
<!-- Android 8+: the system shapes the icon; Android 13+ can tint the
     monochrome layer to match the wallpaper. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""


def svg(
    circles: list[tuple[float, float, float, str]], *, width: float, height: float, extra: str = ""
) -> str:
    body = "\n".join(
        f'  <circle cx="{x:.1f}" cy="{y:.1f}" r="{r:.1f}" fill="{colour}"/>'
        for x, y, r, colour in circles
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width:g} {height:g}" '
        f'width="{width:g}" height="{height:g}">\n{extra}{body}\n</svg>\n'
    )


def scaled(
    circles: list[tuple[float, float, float, str]], size: float, dx: float = 0, dy: float = 0
):
    return [(x * size + dx, y * size + dy, r * size, c) for x, y, r, c in circles]


# ---------------------------------------------------------------------------
def main() -> None:
    # Android launcher icons. The adaptive foreground keeps the mark inside the
    # 66dp safe zone of the 108dp canvas, which any mask shape leaves visible.
    safe = 0.74
    for folder, size in {
        "mdpi": 48,
        "hdpi": 72,
        "xhdpi": 96,
        "xxhdpi": 144,
        "xxxhdpi": 192,
    }.items():
        save_png(icon_png(size, shape="rounded"), ANDROID_RES / f"mipmap-{folder}/ic_launcher.png")
        save_png(
            icon_png(size, shape="circle"), ANDROID_RES / f"mipmap-{folder}/ic_launcher_round.png"
        )
    drawable = ANDROID_RES / "drawable"
    (drawable / "ic_launcher_background.xml").write_text(GRADIENT_BACKGROUND, encoding="utf-8")
    (drawable / "ic_launcher_foreground.xml").write_text(
        vector_drawable(
            mark(safe, dots=WHITE, accent=NAVY),
            dp=108,
            viewport=108,
            comment="The launcher icon's mark.",
        ),
        encoding="utf-8",
    )
    (drawable / "ic_launcher_monochrome.xml").write_text(
        vector_drawable(
            mark(safe, dots=WHITE, accent=WHITE),
            dp=108,
            viewport=108,
            comment="The themed-icon layer: one colour, which Android tints.",
        ),
        encoding="utf-8",
    )
    # The status-bar icon must be a single colour on transparent; Android paints
    # it. The mark fills nearly all of it, since 24dp is small.
    (drawable / "ic_notification.xml").write_text(
        vector_drawable(
            mark(1.38, dots=WHITE, accent=WHITE),
            dp=24,
            viewport=24,
            comment="The notification icon.",
        ),
        encoding="utf-8",
    )
    (drawable / "launch_mark.xml").write_text(
        vector_drawable(
            mark(1.38, dots=ORANGE, accent=NAVY),
            dp=120,
            viewport=120,
            comment="The mark on the launch screen.",
        ),
        encoding="utf-8",
    )
    anydpi = ANDROID_RES / "mipmap-anydpi-v26"
    anydpi.mkdir(parents=True, exist_ok=True)
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        (anydpi / name).write_text(ADAPTIVE_ICON, encoding="utf-8")

    # iOS: every size its catalogue lists, full bleed (iOS rounds the corners) and
    # with no transparency, as the App Store requires.
    contents = json.loads((IOS_ICONS / "Contents.json").read_text(encoding="utf-8"))
    for entry in contents["images"]:
        points = float(entry["size"].split("x")[0])
        pixels = round(points * int(entry["scale"].rstrip("x")))
        save_png(icon_png(pixels, shape="square"), IOS_ICONS / entry["filename"])

    # Brand files for the stores and the docs.
    save_png(icon_png(512, shape="square"), BRAND / "play-store-icon-512.png")
    gradient = (
        '  <defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1">'
        f'<stop offset="0" stop-color="{ORANGE_LIGHT}"/>'
        f'<stop offset="1" stop-color="{ORANGE}"/></linearGradient></defs>\n'
        f'  <rect width="1024" height="1024" rx="{CORNER * 1024:.1f}" fill="url(#g)"/>\n'
    )
    (BRAND / "hoodora-icon.svg").write_text(
        svg(scaled(mark(dots=WHITE, accent=NAVY), 1024), width=1024, height=1024, extra=gradient),
        encoding="utf-8",
    )
    (BRAND / "hoodora-mark.svg").write_text(
        svg(scaled(mark(1.38, dots=ORANGE, accent=NAVY), 256), width=256, height=256),
        encoding="utf-8",
    )
    wordmark = (
        f'  <rect width="1600" height="480" fill="{CREAM}"/>\n'
        '  <text x="456" y="307" font-weight="800" font-size="173" letter-spacing="-4" '
        'font-family="Bricolage Grotesque, DejaVu Sans, Arial, sans-serif" '
        f'fill="{NAVY}">hoodora</text>\n'
    )
    (BRAND / "hoodora-logo.svg").write_text(
        svg(
            scaled(mark(1.111, dots=ORANGE, accent=NAVY), 480),
            width=1600,
            height=480,
            extra=wordmark,
        ),
        encoding="utf-8",
    )
    print("Brand assets written.")  # noqa: T201 — a script run by hand


if __name__ == "__main__":
    main()
